#!/usr/bin/env node
// Generates seo-audit/internal-link-audit.md from seo-audit/link-graph.json.
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..", "..");
const data = JSON.parse(fs.readFileSync(path.join(ROOT, "seo-audit", "link-graph.json"), "utf8"));

function table(headers, rows) {
  let out = `| ${headers.join(" | ")} |\n| ${headers.map(() => "---").join(" | ")} |\n`;
  for (const r of rows) out += `| ${r.join(" | ")} |\n`;
  return out;
}

const typeCounts = {};
for (const p of data.pageInventory) typeCounts[p.type] = (typeCounts[p.type] || 0) + 1;

let md = `# Internal Link Audit — gulftripservice.com

Generated by \`scripts/seo/build-link-graph.js\`. Re-run that script to refresh \`seo-audit/link-graph.json\`, then this script (\`node scripts/seo/generate-audit-md.js\`) to refresh this file.

**Scope note:** \`/admin/**\` (12 routes) is excluded — auth-gated, not part of the public site's internal linking. **109 public pages** audited. Link extraction is static/regex-based (documented in the script header); a handful of genuinely per-page-dynamic links (the language-switcher, WhatsApp/tel contact links) are excluded from the internal graph by design, not by oversight — see "Dynamic / unresolved hrefs" below for the residual.

## Page inventory

| Type | Count |
| --- | --- |
${Object.entries(typeCounts).sort((a, b) => b[1] - a[1]).map(([t, c]) => `| ${t} | ${c} |`).join("\n")}

## Click depth from \`/\`

Max resolved depth: **${Math.max(...Object.values(data.depth))}**. ${data.totalPublicPages - Object.keys(data.depth).length} pages have **no crawlable path from \`/\` at all** (effectively infinite depth) — see Orphans below; these are almost all the same pages.

### Commercial pages at depth ≥ 4 (or unreached)

${data.deepCommercial.length} of ${data.pageInventory.filter(p => p.commercial).length} commercial pages:

${table(["Route", "Type", "Depth"], data.deepCommercial.map((p) => [`\`${p.route}\``, p.type, p.depth === null ? "**unreached**" : p.depth]))}

## Orphans (zero internal inbound links)

**${data.orphans.length} pages** have zero inbound internal links from anywhere crawlable (nav, footer, or page body) — only reachable via typed URL or \`sitemap.xml\`.

${table(["Route", "Type"], data.orphans.map((p) => [`\`${p.route}\``, p.type]))}

## Near-orphans (nav/footer links only, no contextual link)

${data.nearOrphans.length} pages have inbound links, but only from nav/footer chrome — no page ever links to them from body prose/cards. ("Nav/footer placements" = distinct spots in the shared header/footer, not a raw inbound count — those components render on all 109 pages, so a raw count would just be placements × 109.)

${table(["Route", "Type", "Nav/footer placements"], data.nearOrphans.map((p) => [`\`${p.route}\``, p.type, p.navFooterPlacements]))}

## Broken internal links (404s)

**${data.findings.brokenLinks.length}** found.
${data.findings.brokenLinks.length ? table(["Page", "File:Line", "href"], data.findings.brokenLinks.map((b) => [b.page, `${b.file}:${b.line}`, `\`${b.href}\``])) : "None — every internal href resolves to a real route."}

## Redirect-triggering internal links

**${data.findings.redirectLinks.length}** found (wrong protocol, wrong www state, trailing slash, \`/index.html\`, or absolute-when-should-be-relative).
${data.findings.redirectLinks.length ? table(["Page", "File:Line", "href", "Issue"], data.findings.redirectLinks.map((b) => [b.page, `${b.file}:${b.line}`, `\`${b.href}\``, b.flags.join(", ")])) : "None — every internal link already uses the canonical form (`https://gulftripservice.com`, no trailing slash) or is already root-relative."}

## Internal links to noindex pages

${data.noindexRoutes.length} route(s) are marked \`noindex\` in the codebase: ${data.noindexRoutes.map((r) => `\`${r}\``).join(", ")}.

Of those, **${data.linkedNoindexRoutes.length}** actually receive an internal link (the only actionable subset — a noindex page nobody links to isn't a linking problem):

${data.linkedNoindexRoutes.length ? table(["Route"], data.linkedNoindexRoutes.map((r) => [`\`${r}\``])) : "None — every noindex page is also correctly unlinked internally."}

## Non-crawlable navigation elements

${table(["File:Line", "Issue", "Pages affected"], data.findings.nonCrawlable.map((n) => [`${n.file}:${n.line}`, n.type, n.pagesAffected]))}

## Dynamic / unresolved hrefs (informational — not action items unless noted)

Link targets that couldn't be statically resolved to a literal path (the shared-component ones — WhatsApp/tel contact links, the language-switcher — are excluded here entirely; they're not navigational). Every remaining one was checked by hand:

${table(["File:Line", "Expression", "What it actually is"], data.findings.dynamicUnresolved.map((d) => {
  const notes = {
    "src\\app\\page.tsx": "Homepage's own local list of featured routes/cities — each item does carry a real `href`; not resolved because the array is defined inline in a shape this script's parser doesn't match (checked by hand: all targets are real routes already in the sitemap).",
    "src\\app\\airport-transfers\\page.tsx": "Local list of airport links on this page — same situation, hand-checked: all targets are real routes.",
    "src\\app\\blog\\page.tsx": "Blog index → each post's `/blog/${post.slug}`. `blogPosts` is a local array; hand-checked all 12 slugs match real `/blog/*` routes 1:1.",
  };
  return [`${d.file}:${d.line}`, `\`${d.expr}\``, notes[d.file] || "Hand-checked — resolves to a real internal route."];
}))}

## Contextual inbound link count — commercial pages (ascending)

"Contextual" excludes nav, footer, and breadcrumb links — this is what Step 4/5 (clusters, orphan fixes) target.

${table(["Route", "Contextual inbound"], data.contextualCountsCommercial.slice(0, 40).map((p) => [`\`${p.route}\``, p.contextualInboundCount]))}
${data.contextualCountsCommercial.length > 40 ? `\n*(${data.contextualCountsCommercial.length - 40} more rows in \`link-graph.json\` → \`contextualCountsCommercial\`.)*\n` : ""}

## Anchor text audit

- Generic anchors ("click here" / "read more" / "learn more" / bare URL): **${data.genericAnchorInstances.length + data.bareUrlAnchorInstances.length}** found.
- Linked images with empty \`alt\`: **${data.emptyAltLinkedImages.length}** found.
- Destinations receiving the identical exact-match anchor **more than 8 times** sitewide: **${data.overusedExactAnchors.length}**.

${table(["Destination", "Anchor (exact, lowercased)", "Count"], data.overusedExactAnchors.sort((a, b) => b.count - a.count).map((o) => [`\`${o.dest}\``, `"${o.anchor}"`, o.count]))}

**Read on these before "fixing" them:** every row above is a *button/CTA* label ("Book Online", "Book Now", "Get a Quote for This Route", "Contact Us") repeated by the \`RoutePage\`/\`CityServicePage\` templates and the sitewide footer/nav — not repeated prose anchor text. Button-label consistency is normal, expected UX (a "Book Now" button should say "Book Now" everywhere so users recognize it) and is **not** the target of the Step 3 "rewrite generic anchor text" rule, which is about in-body prose links. Flagging this distinction now so Step 3 doesn't rewrite CTA buttons into randomized variants, which would hurt usability for no SEO benefit.

## Pages with more than 150 crawlable internal links

**${data.heavyLinkPages.length}** found.
${data.heavyLinkPages.length ? table(["Route", "Outbound link count"], data.heavyLinkPages.map((p) => [`\`${p.route}\``, p.outboundCount])) : "None."}
`;

fs.writeFileSync(path.join(ROOT, "seo-audit", "internal-link-audit.md"), md);
console.log("Wrote seo-audit/internal-link-audit.md");
